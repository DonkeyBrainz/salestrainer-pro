"""LLM-judge layer: scores qualitative rubric dimensions per scenario.

Reuses the same LLMProvider abstraction as production code. Judge scores are
a soft quality signal — they never affect a scenario's deterministic
pass/fail. One structured call scores all dimensions at once (cost control),
at temperature=0 with a mandatory rationale per dimension.
"""

import logging

from pydantic import BaseModel, Field

from app.llm_providers import ChatMessage, ChatRole, LLMProvider
from evals.judge.rubric import RubricDimension
from evals.report.models import JudgeDimensionScore, ScenarioResult

logger = logging.getLogger(__name__)


class DimensionScore(BaseModel):
    """Judge's score for one rubric dimension."""

    dimension: str
    score: int = Field(ge=1, le=5)
    rationale: str


class JudgeVerdict(BaseModel):
    """Structured judge output: all dimensions scored in one call."""

    dimension_scores: list[DimensionScore]


def _format_transcript(result: ScenarioResult) -> str:
    """Render the scenario's captured transcript for the judge prompt."""
    lines: list[str] = []
    for turn in result.turns:
        lines.append(f"SALESPERSON: {turn.salesperson_message}")
        lines.append(f"CUSTOMER (mood={turn.mood_after}): {turn.response_text}")
        if turn.objections_raised_after != turn.objections_raised_before:
            new = set(turn.objections_raised_after) - set(turn.objections_raised_before)
            lines.append(f"[objection raised: {', '.join(sorted(new))}]")
    for case in result.cases:
        lines.append(f"SALESPERSON: {case.salesperson_message}")
        lines.append(f"COACH ANALYSIS: {case.analysis}")
    for vturn in result.voice_turns:
        lines.append(f"SALESPERSON (spoken): {vturn.salesperson_text}")
        if vturn.input_transcription:
            lines.append(f"[model heard: {vturn.input_transcription}]")
        lines.append(f"CUSTOMER (spoken): {vturn.response_text}")
    return "\n".join(lines)


def _build_judge_prompt(
    result: ScenarioResult, dimensions: tuple[RubricDimension, ...], context: str
) -> str:
    """Build the rubric-anchored judge prompt."""
    rubric_lines = []
    for d in dimensions:
        rubric_lines.append(
            f"- {d.name}: {d.description}\n  1 = {d.anchor_low}\n  5 = {d.anchor_high}"
        )
    rubric_text = "\n".join(rubric_lines)

    return f"""You are an expert evaluator of AI sales-training agents.

{context}

## Transcript
{_format_transcript(result)}

## Rubric
Score each dimension independently on a 1-5 integer scale using the anchors:
{rubric_text}

For every dimension provide a one-or-two-sentence rationale citing specific
evidence from the transcript. Score all dimensions listed above, exactly once
each, using the exact dimension names given."""


async def judge_scenario(
    result: ScenarioResult,
    dimensions: tuple[RubricDimension, ...],
    provider: LLMProvider,
    judge_model: str,
    context: str,
) -> list[JudgeDimensionScore] | None:
    """Score one scenario result against the rubric. Returns None on failure."""
    prompt = _build_judge_prompt(result, dimensions, context)
    try:
        completion = await provider.complete_structured(
            [ChatMessage(ChatRole.USER, prompt)],
            response_schema=JudgeVerdict,
            model=judge_model,
            temperature=0.0,
            max_output_tokens=2048,
        )
    except Exception as e:  # noqa: BLE001 - judge failure must not fail the run
        logger.warning(f"Judge call failed for {result.scenario_id}: {e}")
        return None

    if not isinstance(completion.parsed, JudgeVerdict):
        logger.warning(f"Judge produced no structured output for {result.scenario_id}")
        return None

    valid_names = {d.name for d in dimensions}
    return [
        JudgeDimensionScore(dimension=s.dimension, score=s.score, rationale=s.rationale)
        for s in completion.parsed.dimension_scores
        if s.dimension in valid_names
    ]


